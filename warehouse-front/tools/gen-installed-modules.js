const fs = require('fs');
const path = require('path');

const MODULES_DIR = path.resolve(__dirname, '..', 'src', 'app', 'modules');
const TARGET_FILE = path.join(MODULES_DIR, 'installed-modules.ts');

function getDiscoveredModules() {
  if (!fs.existsSync(MODULES_DIR)) return [];
  const entries = fs.readdirSync(MODULES_DIR, { withFileTypes: true });
  const modules = [];
  for (const entry of entries) {
    if (entry.isDirectory() && entry.name !== 'common') {
      const moduleFile = path.join(MODULES_DIR, entry.name, 'module.ts');
      if (fs.existsSync(moduleFile)) {
        modules.push(entry.name);
      }
    }
  }
  return modules.sort();
}

function resolveSelectedModules(rawModules) {
  const discovered = getDiscoveredModules();
  if (!rawModules || !rawModules.trim()) {
    return discovered;
  }
  const requested = rawModules
    .split(',')
    .map(s => s.trim().toLowerCase())
    .filter(Boolean);

  if (requested.length === 0 || requested.includes('all')) {
    return discovered;
  }
  return discovered.filter(m => requested.includes(m));
}

function generateInstalledModulesContent(selectedModules) {
  const sorted = [...selectedModules].sort();
  const imports = sorted.map(m => `import { MODULE as ${m}Module } from './${m}/module';`).join('\n');
  const items = sorted.map(m => `  ${m}Module,`).join('\n');

  return `// This file is auto-generated by tools/gen-installed-modules.js.
// Committed version contains all modules. During build, build-for-modules.js generates
// a subset based on WH_MODULES and restores the committed version after build.

import { WhFrontendModule } from '../core/modules/module-contract';
${imports ? imports + '\n' : ''}
export const INSTALLED_MODULES: WhFrontendModule[] = [
${items}
];
`;
}

function generateInstalledModules(rawModules = process.env.WH_MODULES) {
  const selected = resolveSelectedModules(rawModules);
  const content = generateInstalledModulesContent(selected);
  fs.writeFileSync(TARGET_FILE, content, 'utf8');
  console.log(`[gen-installed-modules] ✔ Generated installed-modules.ts with [${selected.join(', ')}]`);
  return selected;
}

if (require.main === module) {
  let argModules = process.env.WH_MODULES;
  for (let i = 2; i < process.argv.length; i++) {
    const arg = process.argv[i];
    if (arg.startsWith('--modules=')) {
      argModules = arg.slice('--modules='.length);
    } else if (arg === '--all') {
      argModules = '';
    }
  }
  generateInstalledModules(argModules);
}

module.exports = {
  getDiscoveredModules,
  resolveSelectedModules,
  generateInstalledModulesContent,
  generateInstalledModules,
  TARGET_FILE
};

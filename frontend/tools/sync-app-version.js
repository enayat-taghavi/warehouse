/**
 * همگام‌سازی شمارهٔ نسخه از یک منبع (طرح ۵ اندروید، د۱).
 *
 * تنها منبع: فیلد `version` در frontend/package.json (قالب MAJOR.MINOR.PATCH).
 * خروجی‌ها:
 *   - src/app/core/platform/app-version.ts  (APP_VERSION برای سربرگ، اعلان و Live Update)
 *   - android/app/version.properties         (versionName و versionCode برای گریدل)
 * versionCode = MAJOR*10000 + MINOR*100 + PATCH (فرعی و اصلاحی باید زیر ۱۰۰ باشند).
 * اگر محتوا همان باشد چیزی نوشته نمی‌شود. نسخهٔ نادرست ساخت را با کد ۱ متوقف می‌کند.
 *
 * استفاده: node tools/sync-app-version.js [--root <frontend dir>]
 */
const fs = require('fs');
const path = require('path');

function parseStrictVersion(version) {
  const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(version ?? '').trim());
  if (!m) return null;
  const [major, minor, patch] = m.slice(1).map((n) => parseInt(n, 10));
  if (minor > 99 || patch > 99) return null;
  return { major, minor, patch };
}

function versionCodeOf(version) {
  const p = parseStrictVersion(version);
  if (!p) throw new Error(`Invalid version: ${version}`);
  return p.major * 10000 + p.minor * 100 + p.patch;
}

function renderAppVersionTs(version) {
  return [
    "// این فایل را دستی ویرایش نکنید: tools/sync-app-version.js از package.json می‌سازد.",
    "export type AppChannel = 'direct' | 'bazaar' | 'myket';",
    '',
    `export const APP_VERSION = '${version}';`,
    '',
  ].join('\n');
}

function renderVersionProperties(version) {
  return [
    '# Generated by frontend/tools/sync-app-version.js from package.json; do not edit by hand.',
    `versionName=${version}`,
    `versionCode=${versionCodeOf(version)}`,
    '',
  ].join('\n');
}

function writeIfChanged(file, content) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf8');
  return true;
}

function syncAppVersion(root) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const version = String(pkg.version ?? '').trim();
  if (!parseStrictVersion(version)) {
    throw new Error(`package.json version "${pkg.version}" is not MAJOR.MINOR.PATCH (minor/patch < 100)`);
  }
  const changed = [];
  const tsFile = path.join(root, 'src', 'app', 'core', 'platform', 'app-version.ts');
  if (writeIfChanged(tsFile, renderAppVersionTs(version))) changed.push(tsFile);
  const propsFile = path.join(root, 'android', 'app', 'version.properties');
  if (writeIfChanged(propsFile, renderVersionProperties(version))) changed.push(propsFile);
  return { version, versionCode: versionCodeOf(version), changed };
}

module.exports = { parseStrictVersion, versionCodeOf, syncAppVersion };

if (require.main === module) {
  const rootIdx = process.argv.indexOf('--root');
  const root = rootIdx > -1 ? path.resolve(process.argv[rootIdx + 1]) : path.resolve(__dirname, '..');
  try {
    const result = syncAppVersion(root);
    const note = result.changed.length ? `updated ${result.changed.length} file(s)` : 'no change';
    console.log(`[sync-app-version] ${result.version} (versionCode ${result.versionCode}): ${note}`);
  } catch (err) {
    console.error(`[sync-app-version] ✖ ${err.message}`);
    process.exit(1);
  }
}

/**
 * تشخیص «به بک‌اند نرسیدیم» از «بک‌اند جواب داد و نپذیرفت»
 *
 * این تفکیک، مرز میان نگه‌داشتن داده کاربر و نابود کردن آن است، پس در یک
 * جای واحد نگه داشته می‌شود تا دو نقطه‌ی مصرف هرگز از هم واگرا نشوند:
 *   • offline.interceptor.ts  — تصمیم fallback به کش / صف
 *   • offline-sync.service.ts — گزارش وضعیت اتصال هنگام پردازش صف
 *
 * چرا فقط 0 و 504 کافی نیست: در محیط عملیاتی برنامه پشت Cloudflare است.
 * وقتی سرور اصلی (origin) خاموش شود یا تونل قطع شود، Cloudflare خودش سالم
 * است و یک پاسخ HTTP کامل و معتبر برمی‌گرداند — در عمل معمولاً 502، نه 504.
 * برای مرورگر این «موفقیت» است، پس بدون این لیست:
 *   • GET به کش fallback نمی‌کرد → کاربر به‌جای داده آفلاین، خطا می‌دید
 *   • POST/PATCH وارد صف نمی‌شد → رکورد کاربر از بین می‌رفت
 *
 *   0        خطای شبکه، یا مهلت تمام‌شده‌ی شبکه‌ی کند
 *   502      Bad Gateway — دروازه به origin نرسید
 *   503      Service Unavailable — سرویس بالا نیست
 *   504      Gateway Timeout — origin دیر جواب داد
 *   520–530  کدهای اختصاصی Cloudflare، همه مربوط به مشکل origin:
 *            521 سرور خاموش، 522 اتمام مهلت اتصال، 523 origin غیرقابل‌دسترس،
 *            524 اتمام مهلت پاسخ، 525/526 مشکل SSL،
 *            530 خطاهای سری ۱۰۰۰ — از جمله «Error 1033: Cloudflare Tunnel error»
 *            که وقتی cloudflared خاموش باشد رخ می‌دهد (با آزمایش روی محیط
 *            عملیاتی همین پروژه تأیید شد: خاموش کردن تونل → همه‌ی مسیرها 530)
 *
 * توجه درباره 503: حتی اگر از خود Django بیاید هم اینجا امن است. بدترین
 * پیامدش این است که یک تغییر را در صف نگه داریم و کمی بعد بفرستیم؛ در حالی
 * که پیامد اشتباه مقابل، نابودی کار کاربر است.
 */
export const isServerUnreachable = (status: number): boolean =>
  status === 0 ||
  status === 502 ||
  status === 503 ||
  status === 504 ||
  (status >= 520 && status <= 530);
